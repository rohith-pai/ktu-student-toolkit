-- KTU Student Toolkit - ETLab data schema for Supabase PostgreSQL
-- Run this in the Supabase SQL Editor (Project -> SQL Editor -> New query).

create extension if not exists pgcrypto;

create table if not exists students (
    id                  bigint generated by default as identity primary key,
    etlab_user_id       text unique,
    username            text,
    university_reg_no   text,
    roll_number         text,
    name                text,
    gender              text,
    date_of_birth       date,
    phone               text,
    email               text,
    raw_profile         jsonb,
    updated_at          timestamptz not null default now()
);

create table if not exists guardians (
    id          bigint generated by default as identity primary key,
    student_id  bigint not null references students(id) on delete cascade,
    father      jsonb,
    mother      jsonb,
    raw         jsonb,
    updated_at  timestamptz not null default now()
);

create table if not exists bank_accounts (
    id          bigint generated by default as identity primary key,
    student_id  bigint not null references students(id) on delete cascade,
    details     jsonb,
    updated_at  timestamptz not null default now()
);

create table if not exists subjects (
    subject_code    text primary key,
    subject_name    text,
    type            text,
    updated_at      timestamptz not null default now()
);

create table if not exists teachers (
    id      bigint generated by default as identity primary key,
    name    text not null,
    email   text,
    phone   text,
    role    text,
    unique (name, email)
);

-- Safe to re-run on an existing database.
alter table teachers add column if not exists role text;

create table if not exists teacher_subjects (
    teacher_id      bigint not null references teachers(id) on delete cascade,
    subject_code    text not null references subjects(subject_code) on delete cascade,
    primary key (teacher_id, subject_code)
);

create table if not exists timetable_slots (
    id              bigint generated by default as identity primary key,
    student_id      bigint not null references students(id) on delete cascade,
    day             text not null,
    period          integer not null,
    subject_code    text references subjects(subject_code),
    teacher_id      bigint references teachers(id),
    raw_text        text,
    updated_at      timestamptz not null default now()
);

create table if not exists attendance_summary (
    id              bigint generated by default as identity primary key,
    student_id      bigint not null references students(id) on delete cascade,
    subject_code    text not null references subjects(subject_code) on delete cascade,
    present_hours   integer,
    total_hours     integer,
    percentage      numeric(5,2),
    updated_at      timestamptz not null default now(),
    unique (student_id, subject_code)
);

create table if not exists attendance_daily (
    id              bigint generated by default as identity primary key,
    student_id      bigint not null references students(id) on delete cascade,
    attendance_date date not null,
    period          integer not null,
    status          text not null,
    subject_code    text,
    topic           text,
    updated_at      timestamptz not null default now()
);

create table if not exists marks (
    id              bigint generated by default as identity primary key,
    student_id      bigint not null references students(id) on delete cascade,
    subject_code    text not null references subjects(subject_code) on delete cascade,
    exam            text,
    max_marks       numeric(6,2),
    marks_obtained  numeric(6,2),
    updated_at      timestamptz not null default now()
);

create table if not exists university_results (
    id                  bigint generated by default as identity primary key,
    student_id          bigint not null references students(id) on delete cascade,
    semester            integer not null,
    sgpa                numeric(4,2),
    cgpa                numeric(4,2),
    earned_credits      numeric(5,2),
    total_credits       numeric(5,2),
    status              text,
    raw                 jsonb,
    updated_at          timestamptz not null default now(),
    unique (student_id, semester)
);

create table if not exists result_subjects (
    id                  bigint generated by default as identity primary key,
    result_id           bigint not null references university_results(id) on delete cascade,
    subject_code        text not null,
    subject_name        text,
    attendance          text,
    attendance_pct      text,
    earned_credits      text,
    total_credits       text,
    grade               text,
    result              text,
    unique (result_id, subject_code)
);

create table if not exists sync_log (
    id          bigint generated by default as identity primary key,
    student_id  bigint references students(id) on delete cascade,
    endpoint    text not null,
    status      text,
    synced_at   timestamptz not null default now()
);

